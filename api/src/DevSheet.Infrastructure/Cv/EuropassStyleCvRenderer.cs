using DevSheet.Application.Cv;
using DevSheet.Domain.Entities;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace DevSheet.Infrastructure.Cv;

/// <summary>
/// "Europass-style" template: follows the Europass section structure (personal information, work experience,
/// education, language table with the five CEFR skills, digital skills, certifications) filled from DevSheet data.
/// It is NOT an official Europass document: it carries no Europass logo and cannot be imported into the Europass editor.
/// See docs/EUROPASS.md.
/// </summary>
public static class EuropassStyleCvRenderer
{
    private const string Blue = "#0e47cb";
    private const string Muted = "#525252";
    private const string Line = "#d4d4d4";
    private const float DateColumn = 105;

    static EuropassStyleCvRenderer()
    {
        QuestPDF.Settings.License = LicenseType.Community; // see ModernCvRenderer for the license note
    }

    public static byte[] Render(CvModel cv) => Build(cv).GeneratePdf();

    internal static Document Build(CvModel cv) =>
        Document.Create(doc => doc.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(36);
            page.DefaultTextStyle(t => t.FontSize(10).FontColor("#171717"));

            page.Content().Column(col =>
            {
                col.Spacing(12);
                Header(col, cv);

                if (!string.IsNullOrWhiteSpace(cv.Summary))
                    Section(col, "About me", c => c.Item().Text(cv.Summary.Trim()));

                if (cv.Experience.Count > 0)
                    Section(col, "Work experience", c =>
                    {
                        foreach (var x in cv.Experience)
                            Entry(c, CvFormat.Range(x.Start, x.End), item =>
                            {
                                item.Item().Text($"{x.Title}").SemiBold();
                                item.Item().Text(x.Company).FontColor(Muted);
                                if (!string.IsNullOrWhiteSpace(x.Description)) item.Item().PaddingTop(2).Text(x.Description.Trim());
                            });
                    });

                if (cv.Education.Count > 0)
                    Section(col, "Education and training", c =>
                    {
                        foreach (var e in cv.Education)
                            Entry(c, CvFormat.Range(e.Start, e.End), item =>
                            {
                                item.Item().Text(string.IsNullOrWhiteSpace(e.Degree) ? e.Institution : e.Degree).SemiBold();
                                if (!string.IsNullOrWhiteSpace(e.Degree)) item.Item().Text(e.Institution).FontColor(Muted);
                            });
                    });

                if (cv.Languages.Count > 0)
                    Section(col, "Language skills", c => Languages(c, cv.Languages));

                if (cv.Skills.Count > 0)
                    Section(col, "Digital and technical skills", c => c.Item().Text(string.Join("  ·  ", cv.Skills)));

                if (cv.Certifications.Count > 0)
                    Section(col, "Certifications", c =>
                    {
                        foreach (var x in cv.Certifications)
                            Entry(c, x.Date is { } d ? CvFormat.Month(d) : "", item =>
                            {
                                item.Item().Text(x.Name).SemiBold();
                                if (!string.IsNullOrWhiteSpace(x.Issuer)) item.Item().Text(x.Issuer).FontColor(Muted);
                                if (!string.IsNullOrWhiteSpace(x.Url))
                                    item.Item().Text(t => t.Hyperlink(x.Url, x.Url).FontSize(8).FontColor(Blue).Underline());
                            });
                    });

                if (cv.Projects.Count > 0)
                    Section(col, "Projects", c =>
                    {
                        foreach (var p in cv.Projects)
                            Entry(c, "", item =>
                            {
                                item.Item().Text(t =>
                                {
                                    t.Span(p.Title).SemiBold();
                                    t.Span("  ");
                                    t.Hyperlink(p.Url, p.Url).FontSize(8).FontColor(Blue).Underline();
                                });
                                if (!string.IsNullOrWhiteSpace(p.Description)) item.Item().Text(p.Description.Trim());
                                if (p.Skills.Count > 0) item.Item().Text(string.Join(", ", p.Skills)).FontSize(9).FontColor(Muted);
                            });
                    });
            });

            page.Footer().AlignCenter().Text("Europass-style CV generated by DevSheet · not an official Europass document")
                .FontSize(7).FontColor(Muted);
        }));

    private static void Header(ColumnDescriptor col, CvModel cv)
    {
        col.Item().BorderBottom(2).BorderColor(Blue).PaddingBottom(6).Column(h =>
        {
            h.Item().Text(cv.Name).FontSize(22).Bold().FontColor(Blue);
            if (!string.IsNullOrWhiteSpace(cv.Headline)) h.Item().Text(cv.Headline).FontSize(12).FontColor(Muted);
            var contact = new[] { cv.Email, cv.Phone, cv.Location, cv.GithubUrl }.Where(s => !string.IsNullOrWhiteSpace(s));
            h.Item().PaddingTop(2).Text(string.Join("  ·  ", contact)).FontSize(9).FontColor(Muted);
        });
    }

    private static void Section(ColumnDescriptor col, string title, Action<ColumnDescriptor> body) =>
        col.Item().Column(c =>
        {
            c.Spacing(6);
            c.Item().Text(title.ToUpperInvariant()).FontSize(11).Bold().FontColor(Blue);
            body(c);
        });

    /// <summary>Europass layout: dates in a narrow left column, details on the right.</summary>
    private static void Entry(ColumnDescriptor col, string dates, Action<ColumnDescriptor> details) =>
        col.Item().EnsureSpace(45).Row(r =>
        {
            r.ConstantItem(DateColumn).Text(dates).FontSize(9).FontColor(Muted);
            r.RelativeItem().Column(details);
        });

    private static void Languages(ColumnDescriptor col, IReadOnlyList<CvLanguage> all)
    {
        var native = all.Where(l => l.IsMotherTongue).Select(l => l.Name).ToList();
        var foreign = all.Where(l => !l.IsMotherTongue).ToList();

        if (native.Count > 0)
            col.Item().Text(t =>
            {
                t.Span("Mother tongue(s): ").SemiBold();
                t.Span(string.Join(", ", native));
            });

        if (foreign.Count == 0) return;
        col.Item().Text("Other language(s)").SemiBold();
        col.Item().Table(table =>
        {
            table.ColumnsDefinition(c =>
            {
                c.RelativeColumn(2.2f);
                for (var i = 0; i < 5; i++) c.RelativeColumn(1);
            });

            // Two header rows, as in the Europass language table: group labels, then the five skills.
            table.Cell().Row(1).Column(1).Element(Head).Text("");
            table.Cell().Row(1).Column(2).ColumnSpan(2).Element(Head).AlignCenter().Text("UNDERSTANDING").Bold().FontSize(8).FontColor(Blue);
            table.Cell().Row(1).Column(4).ColumnSpan(2).Element(Head).AlignCenter().Text("SPEAKING").Bold().FontSize(8).FontColor(Blue);
            table.Cell().Row(1).Column(6).Element(Head).AlignCenter().Text("WRITING").Bold().FontSize(8).FontColor(Blue);

            string[] subs = ["Listening", "Reading", "Spoken interaction", "Spoken production", ""];
            table.Cell().Row(2).Column(1).Element(Head).Text("");
            for (var i = 0; i < 5; i++)
                table.Cell().Row(2).Column((uint)(i + 2)).Element(Head).AlignCenter().Text(subs[i]).FontSize(7).FontColor(Muted);

            uint row = 3;
            foreach (var l in foreign)
            {
                table.Cell().Row(row).Column(1).Element(Body).Text(l.Name).SemiBold();
                CefrLevel?[] levels = [l.Listening, l.Reading, l.SpokenInteraction, l.SpokenProduction, l.Writing];
                for (var i = 0; i < 5; i++)
                    table.Cell().Row(row).Column((uint)(i + 2)).Element(Body).AlignCenter().Text(levels[i]?.ToString() ?? "–");
                row++;
            }
        });
        col.Item().Text("Levels: A1/A2 basic user · B1/B2 independent user · C1/C2 proficient user (Common European Framework of Reference for Languages)")
            .FontSize(7).FontColor(Muted);
    }

    private static IContainer Head(IContainer c) => c.BorderBottom(0.5f).BorderColor(Line).PaddingVertical(2);
    private static IContainer Body(IContainer c) => c.BorderBottom(0.5f).BorderColor(Line).PaddingVertical(3);
}
